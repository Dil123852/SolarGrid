// File: generate-android-icons.mjs
// Purpose: Converts the Circum Icons used by the Android app (from react-icons/ci, the same set
//          the web app uses) into Android VectorDrawable XML under res/drawable/ci_*.xml.
// Usage:   node scripts/generate-android-icons.mjs   (needs `npm install` in web/ first)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(path.join(root, "web/node_modules/react-icons/ci/index.js"), "utf8");
const outDir = path.join(root, "android/app/src/main/res/drawable");

// Circum icon -> drawable name used in Kotlin (R.drawable.ci_*).
const ICONS = {
  CiSun: "ci_sun",
  CiCircleChevLeft: "ci_back",
  CiCircleChevDown: "ci_chevron_down",
  CiViewList: "ci_list",
  CiLogout: "ci_logout",
  CiCirclePlus: "ci_plus",
  CiBatteryCharging: "ci_node",
  CiCalendarDate: "ci_calendar",
  CiCircleCheck: "ci_check",
  CiCircleAlert: "ci_alert",
  CiCircleRemove: "ci_remove",
  CiRepeat: "ci_repeat",
  CiTimer: "ci_timer",
  CiMap: "ci_map",
  CiUser: "ci_user",
  CiBarcode: "ci_scan",
  CiClock2: "ci_clock",
};

// VectorDrawable only understands paths, so circles and rectangles are rewritten as path data.
function circlePath(cx, cy, r) {
  return `M${cx - r},${cy}a${r},${r} 0 1,0 ${r * 2},0a${r},${r} 0 1,0 ${-r * 2},0Z`;
}

function rectPath(x, y, w, h) {
  return `M${x},${y}h${w}v${h}h${-w}Z`;
}

function collectPaths(node, out) {
  const a = node.attr ?? {};
  if (node.tag === "path") out.push(a.d);
  else if (node.tag === "circle") out.push(circlePath(Number(a.cx), Number(a.cy), Number(a.r)));
  else if (node.tag === "rect") out.push(rectPath(Number(a.x ?? 0), Number(a.y ?? 0), Number(a.width), Number(a.height)));
  else if (node.tag !== "svg" && node.tag !== "g") throw new Error(`Unsupported element <${node.tag}>`);
  for (const child of node.child ?? []) collectPaths(child, out);
  return out;
}

for (const [name, drawable] of Object.entries(ICONS)) {
  // Each icon is "module.exports.<Name> = function <Name> (props) { return GenIcon(<json>)(props); };"
  const start = source.indexOf(`module.exports.${name} = function`);
  if (start < 0) throw new Error(`Icon not found: ${name}`);
  const jsonStart = source.indexOf("GenIcon(", start) + "GenIcon(".length;
  const jsonEnd = source.indexOf(")(props)", jsonStart);
  const tree = JSON.parse(source.slice(jsonStart, jsonEnd));
  const [minX, minY, w, h] = tree.attr.viewBox.split(/\s+/).map(Number);
  if (minX !== 0 || minY !== 0) throw new Error(`${name}: unexpected viewBox ${tree.attr.viewBox}`);
  const paths = collectPaths(tree, []);
  const xml = [
    `<?xml version="1.0" encoding="utf-8"?>`,
    `<!-- Circum Icons: ${name} (generated by scripts/generate-android-icons.mjs). Tinted at runtime. -->`,
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"`,
    `    android:width="24dp"`,
    `    android:height="24dp"`,
    `    android:viewportWidth="${w}"`,
    `    android:viewportHeight="${h}">`,
    ...paths.map((d) => `    <path\n        android:fillColor="#FF000000"\n        android:pathData="${d}" />`),
    `</vector>`,
    ``,
  ].join("\n");
  fs.writeFileSync(path.join(outDir, `${drawable}.xml`), xml);
  console.log(`${drawable}.xml  <- ${name} (${paths.length} path${paths.length === 1 ? "" : "s"})`);
}
